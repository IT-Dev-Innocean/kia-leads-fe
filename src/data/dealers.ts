function byName(left: string, right: string) {
  return left.localeCompare(right, "id")
}

export function formatAddress(dealer: Dealer) {
  return [dealer.street, dealer.area, dealer.postalCode].filter(Boolean).join(", ")
}

export function getProvinces() {
  return [...new Set(dealers.map((dealer) => dealer.province))].sort(byName)
}

export function getCities(province: string) {
  return [
    ...new Set(
      dealers
        .filter((dealer) => dealer.province === province)
        .map((dealer) => dealer.city),
    ),
  ].sort(byName)
}

export function getDealers(province: string, city: string) {
  return dealers
    .filter((dealer) => dealer.province === province && dealer.city === city)
    .sort((left, right) => byName(left.name, right.name))
}

export function getDealerByCode(code: string) {
  return dealers.find((dealer) => dealer.code === code)
}
